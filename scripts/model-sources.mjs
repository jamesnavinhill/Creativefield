// Builds native-workflows/model-sources.json: for every model file a workflow requires, where it can be downloaded,
// its size and its SHA-256, read from the publishers' Hugging Face repositories. Re-run it after adding a workflow:
//
//   node scripts/model-sources.mjs            (writes the file, lists files without a public source)
//
// Sources are the official repackaged ComfyUI repositories (every Comfy-Org repo) plus the model makers' own repos
// below. A file that is in none of them (for example a local conversion) stays out and keeps its manual instructions.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "native-workflows", "model-sources.json");
const EXTRA_REPOS = ["VideoRebirthAI/hyperflow-h3-flash"];
/* Custom node packs by the node class names they provide; installed with git into ComfyUI's custom_nodes.
   WITH lists packs a pack needs beside it (HyperFlow loads GGUF files through ComfyUI-GGUF). */
const WITH = { "https://github.com/Video-Rebirth/ComfyUI-HyperFlow-Flash": ["https://github.com/city96/ComfyUI-GGUF"] };
const NODE_PACKS = {
  "https://github.com/city96/ComfyUI-GGUF": ["UnetLoaderGGUF", "UnetLoaderGGUFAdvanced", "CLIPLoaderGGUF", "DualCLIPLoaderGGUF"],
  "https://github.com/Video-Rebirth/ComfyUI-HyperFlow-Flash": ["HyperFlowGGUFLoader", "HyperFlowSigmas"],
};

const api = async (url) => {
  for (let attempt = 0; attempt < 3; attempt++) {
    const response = await fetch(url, { headers: { "user-agent": "CreativeField-model-sources" } });
    if (response.ok) return response.json();
    if (response.status === 404 || response.status === 401) return [];
    await new Promise((resolve) => setTimeout(resolve, 1500 * (attempt + 1)));
  }
  return [];
};

function requiredModels() {
  const files = new Set(), nodes = new Set();
  for (const pack of readdirSync(path.join(root, "native-workflows"))) {
    const file = path.join(root, "native-workflows", pack, "manifest.json");
    if (!existsSync(file)) continue;
    const manifest = JSON.parse(readFileSync(file, "utf8"));
    for (const route of manifest.routes ?? []) for (const need of route.requirements ?? []) {
      if (need.kind === "model" && need.name) files.add(need.name);
      if (need.kind === "node" && need.name) nodes.add(need.name);
    }
  }
  return { files, nodes };
}

const { files, nodes } = requiredModels();
const repos = [...(await api("https://huggingface.co/api/models?author=Comfy-Org&limit=500")).map((m) => m.id), ...EXTRA_REPOS];
const models = {};
for (const repo of repos) {
  const tree = await api(`https://huggingface.co/api/models/${repo}/tree/main?recursive=1`);
  for (const entry of Array.isArray(tree) ? tree : []) {
    if (entry.type !== "file") continue;
    const name = path.posix.basename(entry.path);
    if (!files.has(name) || models[name]) continue;
    models[name] = {
      url: `https://huggingface.co/${repo}/resolve/main/${entry.path.split("/").map(encodeURIComponent).join("/")}`,
      bytes: entry.size,
      ...(entry.lfs?.oid ? { sha256: entry.lfs.oid } : {}),
    };
  }
}
const nodeSources = {};
for (const [repo, classes] of Object.entries(NODE_PACKS)) for (const name of classes) if (nodes.has(name)) nodeSources[name] = { repo, ...(WITH[repo] ? { with: WITH[repo] } : {}) };

const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(OUT, `${JSON.stringify({ about: "Generated by scripts/model-sources.mjs. Where each required model file and custom node can be installed from.", models: sorted(models), nodes: sorted(nodeSources) }, null, 2)}\n`);
const missing = [...files].filter((name) => !models[name]).sort();
console.log(`${Object.keys(models).length} of ${files.size} model files have a public source; ${Object.keys(nodeSources).length} node classes have a repo.`);
if (missing.length) console.log(`Without a public source (manual):\n  ${missing.join("\n  ")}`);
